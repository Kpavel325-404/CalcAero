"""Build the shared, antialiased PSP T8 font atlas (DejaVu license in LICENSES).

No fonts or rasterization libraries are required on the PSP. The generated font.c
is checked in and used by both the native renderer and the host screenshot test.
"""
from pathlib import Path
import math
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
(ROOT / 'build').mkdir(exist_ok=True)
FONT_DIR = Path('/usr/share/fonts/truetype/dejavu')
CHARS = ''.join(chr(i) for i in range(32, 127))
N = len(CHARS)
atlas = Image.new('L', (512, 512))
ImageDraw.Draw(atlas).rectangle((0, 0, 7, 7), fill=255)
x, y, row_height = 0, 16, 0
faces = []
for family, size in [('DejaVuSans.ttf', 11), ('DejaVuSans.ttf', 22), ('DejaVuSansMono.ttf', 11)]:
    font = ImageFont.truetype(str(FONT_DIR / family), size * 4)
    metrics = []
    height = size + 4 if size == 11 else size + 6
    baseline = size
    for char in CHARS:
        advance = round(font.getlength(char) / 4)
        width = math.ceil(font.getlength(char) / 4) + 3
        if x + width + 2 > 512:
            x, y, row_height = 0, y + row_height + 2, 0
        assert y + height < 512, 'Font atlas overflow'
        tile = Image.new('L', (width * 4, height * 4))
        ImageDraw.Draw(tile).text((4, baseline * 4), char, font=font, fill=255, anchor='ls')
        tile = tile.resize((width, height), Image.Resampling.LANCZOS)
        atlas.paste(tile, (x, y))
        metrics.append((x, y, width, height, advance))
        x += width + 2
        row_height = max(row_height, height)
    x, y, row_height = 0, y + row_height + 2, 0
    faces.append(metrics)

# Cache the small rounded key masks. One quad replaces hundreds of vertices;
# the color gradient stays dynamic, so all themes share these same three tiles.
masks = []
for i, (width, height, radius) in enumerate([(73,19,4), (71,17,3), (69,7,2)]):
    tile = Image.new('L', (width*4,height*4))
    ImageDraw.Draw(tile).rounded_rectangle((0,0,width*4-1,height*4-1),radius*4,fill=255)
    tile = tile.resize((width,height), Image.Resampling.LANCZOS)
    u, v = i*80, 260
    atlas.paste(tile,(u,v))
    masks.append((u,v,width,height,0))

header = '''/* Generated by tests/make_font.py. DejaVu: LICENSES/DejaVu-Font.txt. */
#ifndef CL_FONT_H
#define CL_FONT_H
#include <stdint.h>
#define PP_GLYPH_COUNT 95
typedef struct { uint16_t u, v, width, height, advance; } PPGlyph;
extern const PPGlyph pp_glyphs[3][PP_GLYPH_COUNT];
extern const PPGlyph pp_key_masks[3];
extern unsigned char pp_atlas[512 * 512];
#endif
'''
(ROOT / 'src/font.h').write_text(header)
with (ROOT / 'src/font.c').open('w') as f:
    f.write('/* Generated font coverage. See LICENSES/DejaVu-Font.txt. */\n#include "font.h"\n')
    f.write('const PPGlyph pp_glyphs[3][PP_GLYPH_COUNT] = {\n')
    for face in faces:
        f.write('{\n')
        for m in face:
            f.write('{' + ','.join(map(str, m)) + '},\n')
        f.write('},\n')
    f.write('};\nconst PPGlyph pp_key_masks[3] = {\n')
    for m in masks: f.write('{' + ','.join(map(str,m)) + '},\n')
    f.write('};\nunsigned char pp_atlas[512 * 512] __attribute__((aligned(64))) = {\n')
    data = atlas.tobytes()
    for offset in range(0, len(data), 32):
        f.write(','.join(map(str, data[offset:offset+32])) + ',\n')
    f.write('};\n')
atlas.save(ROOT / 'build/font-atlas.png')
print(f'Font atlas: {N} glyphs x 3 faces, 262144 bytes, used height {y}')
